// Generates TypeScript types and standalone validators from the data-product
// JSON Schemas exported by pipeline/ (public/data/v1/schema/).
// The schemas are the source of truth (AGENTS.md section 6); never edit the output by hand.
//
//   npm run gen:data            write src/data/generated/
//   npm run gen:data -- --check fail if src/data/generated/ is out of date

import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { compile } from 'json-schema-to-typescript'

const root = fileURLToPath(new URL('..', import.meta.url))
const schemaDir = join(root, 'public/data/v1/schema')
const outDir = join(root, 'src/data/generated')
const check = process.argv.includes('--check')

// schema file stem -> exported type / validator name
const SCHEMAS = {
  manifest: 'Manifest',
  provinces: 'ProvincesCollection',
  daily: 'ProvinceDaily',
  monthly: 'MonthlySeries',
  cells: 'CellsCollection',
}

const HEADER = '// GENERATED by scripts/gen-data-contract.mjs from public/data/v1/schema/. Do not edit.\n'

const schemas = {}
for (const stem of Object.keys(SCHEMAS)) {
  schemas[stem] = JSON.parse(await readFile(join(schemaDir, `${stem}.schema.json`), 'utf8'))
}

// A property listed in `required` but not described in `properties` is typed
// `unknown` (it must exist, the schema says nothing else). Without this,
// json-schema-to-typescript drops it from the type entirely.
function declareRequired(node) {
  if (Array.isArray(node)) return node.map(declareRequired)
  if (!node || typeof node !== 'object') return node
  const out = Object.fromEntries(Object.entries(node).map(([k, v]) => [k, declareRequired(v)]))
  if (Array.isArray(out.required)) {
    out.properties = { ...out.properties }
    for (const key of out.required) out.properties[key] ??= {}
  }
  return out
}

// Types. additionalProperties: false keeps undeclared fields out of the types
// (it does not change validation, which follows the schemas exactly).
let types = HEADER
for (const [stem, name] of Object.entries(SCHEMAS)) {
  const { title, ...schema } = declareRequired(schemas[stem])
  const ts = await compile({ ...schema, description: title }, name, {
    bannerComment: '',
    additionalProperties: false,
    format: false,
  })
  types += `\n${ts.trim()}\n`
}

// Validators. Dates are checked by the schemas' own `pattern`; `format` is annotation only.
const ajv = new Ajv2020({ code: { source: true, esm: true }, allErrors: false, strict: false, validateFormats: false })
for (const [stem, name] of Object.entries(SCHEMAS)) ajv.addSchema(schemas[stem], `validate${name}`)
const validators = HEADER + '/* eslint-disable */\n' + standaloneCode(ajv)

let validatorTypes = HEADER + "import type { ErrorObject } from 'ajv'\n"
for (const name of Object.values(SCHEMAS)) {
  validatorTypes += `\nexport declare const validate${name}: ((data: unknown) => boolean) & { errors?: ErrorObject[] | null }\n`
}

const outputs = {
  'types.ts': types,
  'validators.js': validators,
  'validators.d.ts': validatorTypes,
}

if (check) {
  const stale = []
  for (const [file, content] of Object.entries(outputs)) {
    const current = await readFile(join(outDir, file), 'utf8').catch(() => null)
    if (current !== content) stale.push(file)
  }
  if (stale.length) {
    console.error(`src/data/generated is out of date (${stale.join(', ')}). Run: npm run gen:data`)
    process.exit(1)
  }
  console.log('src/data/generated is up to date.')
} else {
  await mkdir(outDir, { recursive: true })
  for (const [file, content] of Object.entries(outputs)) await writeFile(join(outDir, file), content)
  console.log(`Wrote ${Object.keys(outputs).map((f) => `src/data/generated/${f}`).join(', ')}`)
}
